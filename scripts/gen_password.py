"""Generate the USERS INSERT statements (with real PBKDF2 hashes) for the seed
data.  The hashing here is identical to ``app/auth.py`` so the demo passwords
documented in the README verify at login.

Run:   python scripts/gen_password.py
It prints SQL you can paste into sql/06_seed.sql.
"""
import hashlib
import os

_ITERATIONS = 100_000
_ALGO = "sha256"
_DK_LEN = 32


def hash_password(password: str):
    salt_hex = os.urandom(16).hex()
    dk = hashlib.pbkdf2_hmac(
        _ALGO, password.encode("utf-8"), bytes.fromhex(salt_hex), _ITERATIONS, _DK_LEN
    )
    return dk.hex(), salt_hex


# (user_id, username, email, full_name, phone, role_id, password)
ACCOUNTS = [
    (1,  "admin", "admin@estatedb.com",  "System Administrator", "555-0100", 1, "Admin@123"),
    (2,  "sarah", "sarah@estatedb.com",  "Sarah Johnson",        "555-0201", 2, "Agent@123"),
    (3,  "mike",  "mike@estatedb.com",   "Mike Chen",            "555-0202", 2, "Agent@123"),
    (4,  "lisa",  "lisa@estatedb.com",   "Lisa Martinez",        "555-0203", 2, "Agent@123"),
    (5,  "david", "david@estatedb.com",  "David Okafor",         "555-0204", 2, "Agent@123"),
    (6,  "john",  "john@example.com",    "John Smith",           "555-0301", 3, "User@123"),
    (7,  "emma",  "emma@example.com",    "Emma Brown",           "555-0302", 3, "User@123"),
    (8,  "alex",  "alex@example.com",    "Alex Turner",          "555-0303", 3, "User@123"),
    (9,  "olivia","olivia@example.com",  "Olivia Davis",         "555-0304", 3, "User@123"),
]


def main():
    print("-- Generated by scripts/gen_password.py")
    for uid, username, email, full_name, phone, role_id, pwd in ACCOUNTS:
        h, salt = hash_password(pwd)
        print(
            "INSERT INTO users (user_id, username, email, password_hash, "
            "password_salt, full_name, phone, role_id) VALUES "
            f"({uid}, '{username}', '{email}', '{h}', '{salt}', "
            f"'{full_name}', '{phone}', {role_id});"
        )


if __name__ == "__main__":
    main()
